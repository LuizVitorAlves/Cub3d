int	ft_count_args(const char *str)
{
	const char	*cpy;
	int			n;

	n = 0;
	cpy = str;
	while (*cpy)
	{
		if (*cpy == '%')
		{
			n++;
		}
		cpy++;
	}
	return (n);
}
